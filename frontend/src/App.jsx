import { useState } from "react";
import "./App.css"
import axios from "axios";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

function App() {

  const [image, setImage] = useState(null);
  const [preview, setPreview] = useState(null);
  const [resultImage, setResultImage] = useState(null);
  const [loading, setLoading] = useState(false);
  const [fileName, setFileName] = useState("");
  const [predictions, setPredictions] = useState([]);
  const [predictionDone, setPredictionDone] = useState(false);
  const [inspectionTime, setInspectionTime] = useState("");

  const API_URL = import.meta.env.VITE_API_URL;

  const handleImageChange = (e) => {

    const file = e.target.files[0];
    
    if(!file) return;
    
    // Clear previous prediction
    setResultImage(null);
    setPredictions([]);
    setPredictionDone(false);

    setImage(file);
    setFileName(file.name);
    setPreview(URL.createObjectURL(file));
    
      console.log(preview);
  };

  const handlePredict = async () => {

    if(!image) {
      alert("Please select an image");
      return;
    }

    setLoading(true);

    const formData = new FormData();

    formData.append("file", image);

    try {

      const response = await axios.post(
        `${API_URL}/predict`,
        formData, 
      );


      setResultImage(`${API_URL}${response.data.predicted_image}?t=${Date.now()}`);
      setPredictions(response.data.predictions);
      setPredictionDone(true);
      setInspectionTime(new Date().toLocaleString());

    } catch (error) {
      console.error(error);
    }

    setLoading(false);
  };

  const getSeverity = (confidence) => {
    if (confidence >= 0.90)
      return "High"

    if (confidence >= 0.70)
      return "Medium"

    return "Low"
  };


const downloadReport = () => {

  const doc = new jsPDF();

  const tableRows = predictions.map((prediction) => [
    prediction.class,
    `${(prediction.confidence * 100).toFixed(2)}%`,
    getSeverity(prediction.confidence)
  ]);

  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");

  doc.text("Industrial Surface Defect Inspection Report", 15, 20);

  doc.setLineWidth(0.5);
  doc.line(15, 25, 195, 25);

  doc.setFontSize(12);
  doc.setFont("helvetica", "normal");

  doc.text(`Inspection Time: ${inspectionTime}`, 15, 40);

  doc.text(
    `Status: ${predictions.length > 0 ? "FAILED" : "PASSED"}`,
    15,
    50
  );

  doc.text(
    `Total Defects: ${predictions.length}`,
    15,
    60
  );

  autoTable(doc, {
    startY: 75,

    head: [
      [
        "Defect Class",
        "Confidence",
        "Severity"
      ]
    ],

    body: tableRows,

    theme: "grid",

    headStyles: {
      fillColor: [13, 110, 253],
      textColor: 255
    },

    styles: {
      halign: "center"
    }
  });

  doc.setFontSize(10);

  doc.text(
    "Generated by Industrial Surface Defect Inspection System",
    15,
    doc.lastAutoTable.finalY + 15
  );

  doc.save("Inspection_Report.pdf");
};

  return (
    <div className="container">

      <h1 className="page-title">Industrial Surface Defect Inspection</h1>

      <p className="subtitle">
        AI-powered steel surface defect detection using YOLO
      </p>

      <div className="controls">
      
        <label htmlFor="file-upload" className="upload-btn">
        📁 Choose Image
        </label>

        <input
            id="file-upload"
            type="file"
            accept="image/*"
            onChange={handleImageChange}
        />

        <button onClick={handlePredict} disabled={loading}>
          {loading ? "Processing...": "Predict"}
        </button>

      </div>

      {fileName && (
        <p className="filename">
          Selected: <strong>{fileName}</strong>
        </p>
      )}

      <div className="images">      
        {preview && (
          <div className="card">
            <h3 className="image-heading">Original Image</h3>
            <img 
              src={preview}
              alt="Original"
              className="preview"
              />
          </div>
        )}

        {resultImage && (
          <div className="card">
            <h3 className="image-heading">Prediction Result</h3>
            <img
                src={resultImage}
                alt="Prediction"
                className="preview"
            />
          </div>
        )}
      </div>

      {predictionDone && (
        <div className="report-card">

          <h2 className="report-title">Inspection Report</h2>

          <div className="report-summary">
            <p>
              <strong>Total Defects:</strong> {predictions.length}
            </p>

            <p>
              <strong>Status:</strong>{" "}
              {predictions.length > 0 ? "Failed" : "Passed"}
            </p>

            <p>
              <strong>Inspection Time:</strong>{" "}
              {inspectionTime}
            </p>
          </div>

          <table>
            <thead>
              <tr>
                <th>Defect Class</th>
                <th>Confidence</th>
                <th>Severity</th>
              </tr>
            </thead>

            <tbody>
              {predictions.map((item, index) => (
                <tr key={index}>
                  <td>{item.class}</td>

                  <td>
                    {(item.confidence * 100).toFixed(2)}%
                  </td>
                  <td>
                    <span
                      className={`severity ${getSeverity(item.confidence).toLowerCase()}`}
                    >
                      {getSeverity(item.confidence)}
                    </span>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>

          <button className="download-btn" 
                  onClick={downloadReport}
          >
              📄 Download Report
          </button>

        </div>
      )}

    </div>
  );
}

export default App;